/**
 * 外字・機種依存文字を標準文字に変換する。
 */
export function normalizeGaiji(text: string): string {
  if (!text) return ''

  let result = text
  for (const [gaiji, standard] of Object.entries(GAIJI_MAP)) {
    result = result.replaceAll(gaiji, standard)
  }
  return result
}
